/* Fawry Media bilingual controls.
   Translations are authored beside the corresponding content in HTML:
   data-en="..." data-ar="...".
   The project/portfolio pages additionally include an HTML template for
   content generated by the existing portfolio.js. No JS translation dictionary.
*/
(() => {
  'use strict';
  const KEY = 'agency_language';
  let selected = 'en';
  try { selected = localStorage.getItem(KEY) === 'ar' ? 'ar' : 'en'; } catch (_) {}
  document.documentElement.lang = selected;
  document.documentElement.dir = selected === 'ar' ? 'rtl' : 'ltr';
  let observer = null;
  let queued = false;
  let dynamicEnglishToArabic = null;
  const originalDynamic = new WeakMap();
  const lastDynamic = new WeakMap();
  const ATTRS = ['placeholder', 'aria-label', 'title'];

  function getDynamicMap() {
    if (dynamicEnglishToArabic) return dynamicEnglishToArabic;
    const map = new Map();
    document.querySelectorAll('template[data-i18n-dynamic]').forEach(t => {
      t.content.querySelectorAll('[data-en][data-ar]').forEach(e => map.set(e.getAttribute('data-en'), e.getAttribute('data-ar')));
    });
    dynamicEnglishToArabic = map;
    return map;
  }
  function apply() {
    queued = false;
    if (!document.body) return;
    if (observer) observer.disconnect();
    const isAr = selected === 'ar';
    document.documentElement.lang = selected;
    document.documentElement.dir = isAr ? 'rtl' : 'ltr';
    document.querySelectorAll('[data-en][data-ar]').forEach(el => {
      if (el.closest('template')) return;
      const next = el.getAttribute(isAr ? 'data-ar' : 'data-en');
      if (next !== null && el.textContent !== next) el.textContent = next;
    });
    document.querySelectorAll('[data-en-placeholder], [data-en-aria-label], [data-en-title]').forEach(el => {
      for (const attr of ATTRS) {
        const next = el.getAttribute('data-' + selected + '-' + attr);
        if (next !== null && el.getAttribute(attr) !== next) el.setAttribute(attr, next);
      }
    });
    document.querySelectorAll('.agency-lang-switch').forEach(b => {
      b.textContent = isAr ? 'English' : 'العربية';
      b.setAttribute('aria-label', isAr ? 'Switch to English' : 'التبديل إلى العربية');
      b.lang = isAr ? 'en' : 'ar';
    });
    // Dynamic project cards/details: HTML template stores the two languages.
    const lookup = getDynamicMap();
    if (lookup.size) {
      const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
      let n;
      while ((n = walker.nextNode())) {
        const parent = n.parentElement;
        if (!parent || parent.closest('script,style,svg,pre,code,template,[data-en][data-ar],.agency-lang-switch')) continue;
        const now = n.nodeValue;
        let en = originalDynamic.get(n);
        if (en === undefined || (lastDynamic.has(n) && now !== lastDynamic.get(n))) {
          en = now;
          originalDynamic.set(n, en);
        }
        const trimmed = en.trim();
        const translated = lookup.get(trimmed);
        if (!translated) continue;
        const next = isAr ? en.replace(trimmed, translated) : en;
        if (n.nodeValue !== next) n.nodeValue = next;
        lastDynamic.set(n, next);
      }
    }
    if (observer) observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }
  function schedule() {
    if (queued) return;
    queued = true;
    requestAnimationFrame(apply);
  }
  function setLanguage(lang) {
    selected = lang === 'ar' ? 'ar' : 'en';
    try { localStorage.setItem(KEY, selected); } catch (_) {}
    apply();
  }
  function newButton(extra) {
    const b = document.createElement('button');
    b.type = 'button';
    b.className = 'agency-lang-switch ' + extra;
    b.addEventListener('click', () => setLanguage(selected === 'ar' ? 'en' : 'ar'));
    return b;
  }
  function init() {
    const actions = document.querySelector('.header__actions');
    if (actions && !actions.querySelector('.agency-lang-switch')) actions.insertBefore(newButton('agency-lang-switch--desktop'), actions.firstChild);
    const mobile = document.querySelector('.mobile-nav');
    if (mobile && !mobile.querySelector('.agency-lang-switch')) mobile.appendChild(newButton('agency-lang-switch--mobile'));
    observer = new MutationObserver(mutations => {
      if (mutations.some(m => !m.target.parentElement?.closest?.('template'))) schedule();
    });
    apply();
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init, { once: true });
  else init();
  window.AGENCY_LANGUAGE = { get: () => selected, set: setLanguage };
})();
